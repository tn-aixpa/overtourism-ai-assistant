def answer_question(question: str, data: dict, role: str) -> str:
    """
    Answer questions over scenario data.
    """

    prompt = f"""
You are a {role}. Your task is to answer the user's question based strictly on the provided scenario data.

Follow these rules:
- Answer with the minimum amount of text necessary.
- Do not add explanations, interpretations, or conclusions unless explicitly requested in the question.
- Include only the information needed to directly answer the question.
- When numerical values are included, round them to 2 decimal places.

Scenario Data: {data}
Question: {question}
"""

    return llm_interaction(prompt, lightweight_llm=False)

# ---------------------------------------------------------------------------
# SYNTESIZE MULTIPLE EXPERTS ANSWERS
# ---------------------------------------------------------------------------

def synthesize_llm(message: str, expert_answers: dict) -> str:
    prompt = f"""
You are a policy synthesizer.

Rules:
- Do NOT invent new facts
- Preserve disagreements
- Be concise
- Do NOT add recommendations unless explicitly present

Question:
{message}

Expert answers:
"""

    for role, answer in expert_answers.items():
        prompt += f"\n[{role}]\n{answer}\n"

    return llm_interaction(prompt, lightweight_llm=False)

# ---------------------------------------------------------------------------
# ANSWER GENERATION
# ---------------------------------------------------------------------------

def generate_answer(question: str, language: str, messages_to_include: list, additional_data: list[Any] = None) -> str:
    """
    Generate output message in user language using question and message generated by the agents
    """

    formatted_messages = "\n".join(
        f"- {msg}" for msg in messages_to_include
    )

    additional_context_section = ""
    if additional_data:
        formatted_additional = "\n".join(
            f"- {json.dumps(item, default=str) if not isinstance(item, str) else item}"
            for item in additional_data
        )
        additional_context_section = f"""
## Additional Context
The following supplementary data was collected from the agent state (may include conversation history, extracted problem info, scenarios, expert answers, etc.):
{formatted_additional}
"""

    prompt = f"""You are a helpful assistant tasked with synthesizing information gathered by multiple agents into a clear, accurate final answer.

## User Question
{question}

## Agent Messages
The following messages represent the core findings of the answering process. **Every message below must be reflected in your final answer**, rephrased in natural language as needed:
{formatted_messages}
{additional_context_section}
## Instructions
- **Your answer must incorporate all Agent Messages.** Rephrase them naturally, but do not omit any — even partial or uncertain findings must be represented.
- If a message contains an error or failure that is relevant to the user's question, surface it clearly. If it is purely internal/technical and irrelevant to the user, you may rephrase it in user-friendly terms rather than silently dropping it.
- Use **Additional Context** only to enrich, clarify, or provide background for the Agent Messages — never as a replacement for them.
- If the available information is incomplete, provide the best possible answer from what is available and clearly state what could not be determined.
- Do not expose internal agent names, node names, workflow states, field names, or any system implementation details in your response.
- Write your response in the following language: **{language}**
- Be concise, accurate, and directly address the user's question.

## Final Answer
"""

    return llm_interaction(prompt, lightweight_llm=False)

