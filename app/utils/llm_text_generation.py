import json

from app.utils.llm import llm_interaction, format_messages
from app.agent. state import AgentState

# ---------------------------------------------------------------------------
# ANSWER QUESTION
# ---------------------------------------------------------------------------

INSTRUCTIONS_FOR_INTEGRATED_MODE = """
- Keep the answer as short as possible, NEVER include tables and reduce markdown as much as possible.
"""

def answer_question(state: AgentState, role: str) -> tuple[str, bool]:
    """
    Generate answer to user question using available context data.
    Returns a tuple of (answer, draw) where draw indicates if the user wants a visualization.
    """

    question = state.get_last_user_message().content
    data = state.cognitive.context_data
    messages = state.get_reasoning_context()
    language = state.user_lang
    additional_instructions = INSTRUCTIONS_FOR_INTEGRATED_MODE if state.integrated_mode else ""

    prompt = f"""You are a {role}. Your task is to answer the user's question using only the provided context data.

## Conversation History
{format_messages(messages)}

## Context Data
{data}

## User Question
{question}

## Instructions
- Base your answer **exclusively** on the context data above.
- You may use conversation history only to clarify what the user is asking — never as a source of facts.
- If the context data does not contain enough information to answer, respond with a clear statement such as: "I don't have enough information to answer this question."
- Do not reveal internal system details: agent names, node names, workflow states, field names, or implementation specifics.
- Be concise and directly address the question.
{additional_instructions}
- Respond in: **{language}**

## Output Format
Respond in the following XML format and nothing else:

<response>
    <answer>Your answer here</answer>
    <draw>true or false</draw>
</response>

Set <draw> to true if the user is explicitly asking for a visual representation (e.g. "show me", "plot", "chart", "visualize", "graph", "diagram"). Otherwise set it to false.
"""

    raw = llm_interaction(state, prompt, lightweight_llm=False)

    import re
    answer_match = re.search(r"<answer>(.*?)</answer>", raw, re.DOTALL)
    answer = answer_match.group(1).strip() if answer_match else raw.strip()
    
    if state.integrated_mode:
        draw = False
    else:
        draw_match = re.search(r"<draw>(.*?)</draw>", raw, re.DOTALL)
        draw = draw_match.group(1).strip().lower() == "true" if draw_match else False

    return answer, draw

# ---------------------------------------------------------------------------
# ANSWER GENERATION
# ---------------------------------------------------------------------------

def generate_answer(state: AgentState) -> str:
    """
    Generate output message in user language using question and message generated by the agents
    """

    question = state.get_last_user_message().content,
    language = state.user_lang,
    messages_to_include = state.cognitive.messages_to_include,
    additional_data = state.cognitive.additional_output_information
    additional_instructions = INSTRUCTIONS_FOR_INTEGRATED_MODE if state.integrated_mode else ""

    formatted_messages = "\n".join(
        f"- {msg}" for msg in messages_to_include
    )

    additional_context_section = ""
    if additional_data:
        formatted_additional = "\n".join(
            f"- {json.dumps(item, default=str) if not isinstance(item, str) else item}"
            for item in additional_data
        )
        additional_context_section = f"""
## Additional Context
The following supplementary data was collected from the agent state (may include conversation history, extracted problem info, scenarios, expert answers, etc.):
{formatted_additional}
"""

    prompt = f"""You are a helpful assistant tasked with synthesizing information gathered by multiple agents into a clear, accurate final answer.

## User Input
{question}

## Agent Messages
The following messages represent the core findings of the answering process. They must **all** appear in your final answer, each preserving its original intent:
{formatted_messages}

**Important:** Some messages may be statements (facts, results, confirmations) and others may be questions or prompts for user input. Preserve the intent of each:
- Statements → rephrase as declarative sentences.
- Questions or requests for user input → rephrase as direct questions, never collapse them into a statement.
- Do not merge a question into a preceding statement. Keep them as separate, sequential sentences.
{additional_context_section}
## Instructions
- **Your answer must incorporate all Agent Messages**, each preserving its original intent (statement vs. question).
- If a message contains an error or failure that is relevant to the user's question, surface it clearly. If it is purely internal/technical and irrelevant to the user, rephrase it in user-friendly terms rather than silently dropping it.
- **Agent Messages are your primary and preferred source.** Use Additional Context only as a last resort — specifically when Agent Messages alone leave a gap that would make the answer incomplete or misleading, AND the Additional Context directly fills that gap. Do not use Additional Context to rephrase, expand, or decorate information already covered by Agent Messages.
- Write your response in the following language: **{language}**
- Be concise, accurate, and directly address the user's question.
- **Start your response immediately with the answer content.** Do not begin with any heading, label, title, or prefix such as "Answer:", "## Final Answer", "Chatbot:", or similar — just the answer itself.
{additional_instructions}

## Final Answer
"""

    return llm_interaction(state, prompt, lightweight_llm=False)

